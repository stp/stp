// api3-b4-c2.cpp -- a regression recorded from a client's C API calls, the
// larger sibling of api3-b4-c.cpp: a transition-relation formula over a
// one-hot 5-bit location (at), 8-bit variables k, x, lambda and y, and their
// underscored next-state copies (_at, _k, ...), with shifts by a variable
// amount spelled out as if-then-else barrel shifters, asserted inside a push
// and checked inside a second one. The body is generated from the 2.x
// recording and builds the same formula in the same order: eN is the 2.x
// term of that number, a declared symbol is named after itself (with a
// leading underscore moved to the end: _at is at_), and 2.x's handle copies
// (Expr eB = eA) are folded into their source.

#include "api3_common.hpp"

#include <cstdint>

